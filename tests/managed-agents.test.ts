import { test, expect } from 'bun:test';
import crypto from 'node:crypto';
import express from 'express';
import jwt from 'jsonwebtoken';
import os from 'node:os';
import path from 'node:path';
import fs from 'node:fs';
import managedAgentsRouter, { dispatchScheduledManagedJobs } from '../server/routes/managedAgents.js';
import { query, run } from '../server/db/helpers.js';
import { initDatabase, closeDatabase } from '../server/db/connection.js';

test('managed agent enrollment, atomic dispatch, report and revocation', async () => {
  const previousJwtSecret = process.env.JWT_SECRET;
  const ephemeralJwtSecret = crypto.randomBytes(48).toString('hex');
  process.env.JWT_SECRET = ephemeralJwtSecret;
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'fortress-test-'));
  const app=express();
  app.use(express.json());
  app.use('/api/managed-agents',managedAgentsRouter);
  await initDatabase({type:'sqlite',filePath:path.join(dir,'data.db')});
  await run('INSERT INTO users(id,email,name,role,auth_type) VALUES(?,?,?,?,?)',['admin','admin@example.invalid','Admin','admin','local']);
  const server=app.listen(0,'127.0.0.1');
  try {
    const address=server.address();
    if (!address || typeof address==='string') throw new Error('Unable to bind test server');
    const base='http://127.0.0.1:'+address.port+'/api/managed-agents';
    const adminToken=jwt.sign({id:'admin',role:'admin',authEpoch:0},ephemeralJwtSecret);
    const adminHeaders={Authorization:'Bearer '+adminToken,'Content-Type':'application/json'};
    const api=async(path:string,body:any,headers:Record<string,string>=adminHeaders,method='POST')=>{
      const response=await fetch(base+path,{method,headers,body:body===undefined?undefined:JSON.stringify(body)});
      let data:any;try{data=await response.json()}catch{data={}};
      return {status:response.status,data};
    };
    const denied=await api('/admin/enroll',{name:'fail'}, {'Content-Type':'application/json'});
    expect(denied.status).toBe(401);
    const enrollment=await api('/admin/enroll',{name:'Laptop One'});
    expect(enrollment.status).toBe(201);
    expect(enrollment.data.token.length).toBeGreaterThan(40);
    const id=enrollment.data.id;
    const auth={'Content-Type':'application/json','Authorization':'Bearer '+enrollment.data.token,'X-Fortress-Agent-Id':id};
    const queue=await api('/admin/'+id+'/jobs',{operation:'backup'});
    expect(queue.status).toBe(201);
    expect((await api('/heartbeat',{}, {'Content-Type':'application/json'})).status).toBe(401);
    expect((await api('/heartbeat',{},auth)).status).toBe(200);
    const beforePoll=await api('/admin/'+id,undefined,adminHeaders,'GET');
    expect(beforePoll.data.lastSeen).toBeTruthy();
    expect(beforePoll.data.jobs[0].state).toBe('pending');
    expect(beforePoll.data.jobs[0].startedAt).toBeNull();
    const overlapping=await api('/admin/'+id+'/jobs',{operation:'check'});
    expect(overlapping.status).toBe(409);
    const poll=await api('/poll',{},auth);
    expect(poll.status).toBe(200);
    expect(poll.data.job.id).toBe(queue.data.id);
    const idlePoll=await api('/poll',{},auth);
    expect(idlePoll.data.job.id).toBe(queue.data.id);
    expect(idlePoll.data.resumed).toBe(true);
    const report=await api('/report',{id:queue.data.id,success:true,message:'ok'},auth);
    expect(report.status).toBe(200);
    const repeated=await api('/report',{id:queue.data.id,success:true,message:'ok'},auth);
    expect(repeated.status).toBe(200);
    expect(repeated.data.duplicate).toBe(true);
    const listing=await api('/admin',undefined,adminHeaders,'GET');
    expect(listing.status).toBe(200);
    expect(listing.data[0].jobs[0].state).toBe('success');
    expect(JSON.stringify(listing.data)).not.toContain(enrollment.data.token);
    expect(JSON.stringify(listing.data)).not.toContain('token_hash');
    // Recovery capabilities come from the running agent, not enrollment or heartbeat.
    const sid='a'.repeat(64);
    expect((await api('/admin/'+id+'/jobs',{operation:'restore',request:{snapshotId:sid}})).status).toBe(409);
    await api('/poll',{capabilities:['recovery-v1']},auth);
    expect((await api('/request',{operation:'restore',request:{snapshotId:sid,paths:[]}},auth)).status).toBe(400);
    expect((await api('/request',{operation:'files',request:{snapshotId:sid,directory:'/../Windows'}},auth)).status).toBe(400);
    const list=await api('/request',{operation:'snapshots',request:{offset:0,command:'forbidden'}},auth);
    expect(list.status).toBe(201);
    const claimed=await api('/poll',{capabilities:['recovery-v1']},auth);
    expect(claimed.data.job.request).toEqual({offset:0});
    const snapshotData={snapshots:[{id:sid,time:new Date().toISOString(),hostname:'laptop',paths:['C:\\Users\\test'],secret:'stripped'}],offset:0,hasMore:false};
    expect((await api('/report',{id:list.data.id,success:true,data:snapshotData},auth)).status).toBe(200);
    const saved=await api('/result',{id:list.data.id},auth);
    expect(saved.data.result.snapshots[0].id).toBe(sid);
    expect(saved.data.result.snapshots[0].secret).toBeUndefined();
    const other=await api('/admin/enroll',{name:'Other laptop'});
    const otherAuth={...auth,Authorization:'Bearer '+other.data.token,'X-Fortress-Agent-Id':other.data.id};
    expect((await api('/result',{id:list.data.id},otherAuth)).status).toBe(404);
    expect((await api('/admin/'+other.data.id+'/jobs/'+list.data.id,undefined,adminHeaders,'GET')).status).toBe(404);
    const recovery=await api('/admin/'+id+'/jobs',{operation:'restore',request:{snapshotId:sid,paths:['/C/Users/test/document[1].txt'],restorePath:'C:\\Windows'}});
    expect(recovery.status).toBe(201);
    const running=await api('/poll',{capabilities:['recovery-v1']},auth);
    expect(running.data.job.operation).toBe('restore');
    expect(running.data.job.request.restorePath).toBeUndefined();
    const activity=await api('/admin/activity',undefined,adminHeaders,'GET');
    expect(activity.data).toEqual([{operation:'restore',count:1}]);
    expect((await api('/report',{id:recovery.data.id,success:true,data:{snapshotId:sid,restorePath:'/unsafe'}},auth)).status).toBe(400);
    const recoveryData={snapshotId:sid,restorePath:'C:\\ProgramData\\FortressBackup\\restores\\'+recovery.data.id};
    expect((await api('/report',{id:recovery.data.id,success:true,data:recoveryData},auth)).status).toBe(200);
    expect((await api('/report',{id:recovery.data.id,success:true,data:recoveryData},auth)).data.duplicate).toBe(true);
    const inventory=await api('/admin',undefined,adminHeaders,'GET');
    expect(JSON.stringify(inventory.data)).not.toContain('restorePath');
    expect((await api('/admin/'+id+'/jobs/'+recovery.data.id,undefined,adminHeaders,'GET')).data.result).toEqual(recoveryData);
    const downgradeQueue=await api('/request',{operation:'restore',request:{snapshotId:sid}},auth);
    expect(downgradeQueue.status).toBe(201);
    expect((await api('/poll',{},auth)).data.job).toBeNull();
    expect((await api('/result',{id:downgradeQueue.data.id},auth)).data.state).toBe('failed');
    expect((await api('/request',{operation:'restore',request:{snapshotId:sid}},auth)).status).toBe(409);
    // Two simultaneous scheduler replicas must not create two jobs in one slot.
    const slot=new Date(Date.now()-60000).toISOString();
    const schedule=await api('/admin/'+id+'/schedule',{minutes:15},adminHeaders,'PUT');
    expect(schedule.status).toBe(200);
    await run('UPDATE managed_clients SET next_run_at=? WHERE id=?',[slot,id]);
    await Promise.all([dispatchScheduledManagedJobs(),dispatchScheduledManagedJobs()]);
    const first=await query<{id:string}>('SELECT id FROM managed_jobs WHERE client_id=? AND schedule_slot=?',[id,slot]);
    expect(first).toHaveLength(1);
    await run("UPDATE managed_jobs SET state='success' WHERE id=?",[first[0].id]);
    // A stale due timestamp must not create another finished backup.
    await run('UPDATE managed_clients SET next_run_at=? WHERE id=?',[slot,id]);
    await dispatchScheduledManagedJobs();
    const again=await query<{id:string}>('SELECT id FROM managed_jobs WHERE client_id=? AND schedule_slot=?',[id,slot]);
    expect(again).toHaveLength(1);
    const disabled=await api('/admin/'+id+'/disable',{});
    expect(disabled.status).toBe(200);
    const deniedAfterDisable=await api('/poll',{},auth);
    expect(deniedAfterDisable.status).toBe(401);
    expect((await api('/heartbeat',{},auth)).data.cancel).toBe(true);
  } finally {
    await new Promise<void>(resolve=>server.close(()=>resolve()));
    await closeDatabase();
    fs.rmSync(dir,{recursive:true,force:true});
    if (previousJwtSecret === undefined) delete process.env.JWT_SECRET;
    else process.env.JWT_SECRET = previousJwtSecret;
  }
},30000);

